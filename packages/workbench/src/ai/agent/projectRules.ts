import type { FileSystem } from "../../platform/types";

/**
 * Project rules (proposal B2, O7): `AGENTS.md` is the one source of instructions for every AI that
 * works on the project. The root file applies everywhere; a nested `AGENTS.md` applies to its folder
 * and below, and the nearest one is listed last (it wins where they disagree), as Cursor's CLI and
 * the AGENTS.md convention do. `CLAUDE.md` / `GEMINI.md` are read too when there is no AGENTS.md in
 * that folder, so a project set up for one vendor still works.
 */

export const RULE_FILES = ["AGENTS.md", "CLAUDE.md", "GEMINI.md"] as const;
const MAX_RULES = 12_000;

/** The folders from the root down to `path`'s folder ("" is the root). */
export function foldersOf(path: string | null): string[] {
  const parts = (path ?? "").split("/").slice(0, -1);
  const out = [""];
  for (let i = 0; i < parts.length; i++) out.push(parts.slice(0, i + 1).join("/"));
  return out;
}

export interface RulesFound {
  files: string[];
  text: string;
}

/** The rules that apply to `activePath` (root first, nearest last), cut to a budget. */
export async function projectRules(fs: FileSystem, activePath: string | null): Promise<RulesFound> {
  const files: string[] = [];
  const parts: string[] = [];
  for (const dir of foldersOf(activePath)) {
    for (const name of RULE_FILES) {
      const path = dir ? `${dir}/${name}` : name;
      const text = await fs.readFile(path).catch(() => null);
      if (text === null || !text.trim()) continue;
      files.push(path);
      parts.push(`From ${path}:\n${text.trim()}`);
      break; // one rules file per folder: AGENTS.md first
    }
  }
  let text = parts.join("\n\n");
  if (text.length > MAX_RULES) text = `${text.slice(0, MAX_RULES)}\n… (rules cut: keep AGENTS.md short)`;
  return { files, text };
}

/**
 * One rules source (proposal O7): AGENTS.md → each vendor's own file, so Claude Code, Gemini,
 * Cursor and Copilot all follow the same rules. Each generated file says where it comes from; a
 * file someone wrote by hand (without that line) is never overwritten.
 */
export const VENDOR_RULE_FILES = ["CLAUDE.md", "GEMINI.md", ".cursor/rules/agents.mdc", ".github/copilot-instructions.md"] as const;
export const GENERATED_MARK = "<!-- Generated by TMCode from AGENTS.md: edit AGENTS.md instead. -->";

export function vendorRulesText(path: string, agents: string): string {
  const body = `${GENERATED_MARK}\n\n${agents.trim()}\n`;
  return path.endsWith(".mdc") ? `---\ndescription: Project rules (from AGENTS.md)\nalwaysApply: true\n---\n${body}` : body;
}

/** Writes the vendor files from AGENTS.md; returns what was written and what was left alone. */
export async function syncVendorRules(fs: FileSystem): Promise<{ written: string[]; kept: string[] } | null> {
  const agents = await fs.readFile("AGENTS.md").catch(() => null);
  if (agents === null) return null;
  const written: string[] = [];
  const kept: string[] = [];
  for (const path of VENDOR_RULE_FILES) {
    const now = await fs.readFile(path).catch(() => null);
    if (now !== null && !now.includes(GENERATED_MARK)) {
      kept.push(path);
      continue;
    }
    const dirs = path.split("/").slice(0, -1);
    for (let i = 1; i <= dirs.length; i++) await fs.createDir(dirs.slice(0, i).join("/")).catch(() => undefined);
    const text = vendorRulesText(path, agents);
    if (now !== text) await fs.writeFile(path, text);
    written.push(path);
  }
  return { written, kept };
}
